"""Mathematical/adversarial controls; no compiler assets required."""
import copy
import json
import math
from pathlib import Path
import unittest
from .prototype import analyze
from .run import intersect_normals

POLICY = json.loads((Path(__file__).parent/'policy.json').read_text())


class IsophoteTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.rows = [dict(uv=[x, y], value=200*160**3/((x+64)**2+(y-16)**2+160**2)**1.5,
                         material='uniform', saturated=False, quantized=False)
                    for x in range(-192, 193, 16) for y in range(-128, 129, 16)]
        cls.baseline = analyze(cls.rows, POLICY)

    def test_projection_and_gain_gauge(self):
        gained = analyze([dict(r, value=17*r['value']) for r in self.rows], POLICY)
        for name, m in self.baseline['methods'].items():
            self.assertEqual(m['admission'], 'Conditional')
            self.assertLess(math.dist(m['projection'], [-64, 16]), 1)
            self.assertLess(abs(m['height']-160), 2)
            self.assertLess(math.dist(m['projection'], gained['methods'][name]['projection']), 1e-8)
            self.assertAlmostEqual(m['height'], gained['methods'][name]['height'], places=7)
            self.assertFalse(m['physical_depth_available'])

    def test_gamma_preserves_center_not_height(self):
        result = analyze([dict(r, value=255*(r['value']/255)**.5) for r in self.rows], POLICY)
        for name, m in result['methods'].items():
            self.assertEqual(m['admission'], 'Conditional')
            self.assertLess(math.dist(m['projection'], [-64, 16]), 2)
            self.assertGreater(abs(m['height']-160), 60)
            self.assertLess(m['heldout_relative_rms'], POLICY['maximum_heldout_relative_rms'])

    def test_seam_saturation_shadow_and_normal_guards(self):
        variants = [
            [dict(r, material='other' if r['uv'][0] >= 0 else r['material'],
                  value=r['value']*(.4 if r['uv'][0] >= 0 else 1)) for r in self.rows],
            [dict(r, value=min(255, round(6*r['value'])), saturated=6*r['value'] >= 254.5,
                  quantized=True) for r in self.rows],
            [dict(r, value=0 if r['uv'][0] >= 0 else r['value']) for r in self.rows],
            [dict(r, normal_mismatch=r['uv'][0] >= 0) for r in self.rows]]
        for rows in variants:
            result = analyze(rows, POLICY)
            self.assertTrue(all(m['admission'] == 'Unavailable' for m in result['methods'].values()))

    def test_transport_ambiguity_cannot_be_rejected_photometrically(self):
        # Identical scalar observations can be generated by an apparent virtual
        # source after transport. There is no source-kind label in estimator inputs.
        for m in self.baseline['methods'].values():
            self.assertTrue(m['primary_or_transport_ambiguous'])
            self.assertFalse(m['type_or_orientation_available'])
            real_source = [-64-24/1.05, 16-12/1.05, 160-120/1.05]
            self.assertGreater(math.dist([*m['projection'], m['height']], real_source), 100)

    def test_two_normal_lines_and_parallel_degeneracy(self):
        floor = dict(axis=2, axes=[0, 1], coordinate=0, normal=[0, 0, 1])
        wall = dict(axis=1, axes=[0, 2], coordinate=-128, normal=[0, 1, 0])
        self.assertIsNone(intersect_normals([([-64, 16], floor)]))
        self.assertLess(math.dist(intersect_normals([([-64, 16], floor), ([-64, 160], wall)]), [-64, 16, 160]), 1e-9)

    def test_point_and_flat_spot_axis_ambiguity(self):
        # Both wide flat cones contain every receiver: direction cannot be
        # inferred even with a known finite point location and perfect shading.
        axes = [[0, 0, -1], [.2, 0, -math.sqrt(.96)]]
        for r in self.rows:
            d = [r['uv'][0]+64, r['uv'][1]-16, -160]
            length = math.sqrt(sum(v*v for v in d))
            self.assertTrue(all(sum(a*b for a, b in zip(axis, d))/length > math.cos(math.radians(85)) for axis in axes))
        tangent_gradient = [3*64/(64**2+16**2+160**2), -3*16/(64**2+16**2+160**2), 0]
        self.assertEqual(tangent_gradient[2], 0)
        incoming = [64, -16, 160]
        cosine = sum(a*b for a, b in zip(tangent_gradient, incoming)) / (
            math.sqrt(sum(a*a for a in tangent_gradient))*math.sqrt(sum(a*a for a in incoming)))
        self.assertLess(cosine, .5)  # even this ideal tangent gradient is not the 3D source ray

    def test_input_limits_rank_and_ownership(self):
        original = copy.deepcopy(self.rows)
        analyze(self.rows, POLICY)
        self.assertEqual(self.rows, original)
        with self.assertRaises(ValueError): analyze(self.rows*2, POLICY)
        with self.assertRaises(ValueError): analyze([dict(self.rows[0], value=float('nan'))], POLICY)
        flat = analyze([dict(r, value=1) for r in self.rows], POLICY)
        self.assertTrue(all(m['admission'] == 'Unavailable' for m in flat['methods'].values()))


if __name__ == '__main__':
    unittest.main()
