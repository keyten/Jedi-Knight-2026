#!/usr/bin/env python3
"""Reduce a completed evaluator run to small, non-asset versioned evidence.
SPDX-License-Identifier: GPL-2.0-or-later
"""
import argparse
from pathlib import Path
from adapters import load, digest
from benchmark import write


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--run', type=Path, required=True)
    p.add_argument('--measurement', type=Path, required=True)
    p.add_argument('--output', type=Path, required=True)
    args = p.parse_args(); args.output.mkdir(parents=True, exist_ok=True)
    result = load(args.run, 128*1024*1024); existing = result['existing_data']; cases = []
    for c in result['cases']:
        s = c['sections']; d = s['source_accuracy']; f = s['prediction_accuracy']['surface']
        cases.append(dict(id=c['id'], tp=d.get('true_positive'), fp=d.get('false_positive'), fn=d.get('false_negative'),
            precision=d.get('precision'), recall=d.get('recall'), f1=d.get('f1'),
            rgb_interval_rmse=f['rgb_interval_rmse'], prediction_area_coverage=f['prediction_coverage'],
            existence_brier=s['uncertainty']['existence']['brier']))
    stocks = {}
    for name, r in existing.get('stock', {}).items():
        stocks[name] = {k: r[k] for k in ('candidate_count', 'samples_without_area', 'known_footprint_area',
            'map_area_coverage', 'normal_second_moment_eigenvalues', 'source_rows_sha256', 'all_pages_declared_complete', 'grid')}
        stocks[name]['complete_derived_stream'] = r['complete_derived_stream']
        stocks[name]['qualities'] = r['groups']['map']['qualities']
        stocks[name]['map_sha256'] = r['source']['map_sha256']
        stocks[name]['profile'] = 'UnknownProfile'
        stocks[name]['source_visibility_complete'] = bool(r['source']['visibility_complete'])
        stocks[name]['page_area'] = {k: g['known_footprint_area'] for k, g in r['groups'].items() if k.startswith('page/')}
    compiled = {name: dict(map_sha256=r['readiness']['source']['map_sha256'],
        candidate_count=r['readiness']['candidate_count'], known_footprint_area=r['readiness']['known_footprint_area'],
        heldout_count=r['baselines']['heldout_observations'],
        target_copy_interval_rmse=r['baselines']['target_copy_sanity']['rgb_interval_rmse'],
        zero_interval_rmse=r['baselines']['zero']['rgb_interval_rmse'],
        answer_present='source_answer_metadata' in r,
        public_geometry_sha256=r['baselines']['audit']['geometry_sha256']) for name, r in existing.get('compiled', {}).items()}
    trials = existing['prior_x03_profile_metrics']['trials']; profile = {}
    for allowance in ('0.0', '0.5', '2.0'):
        records = [r['sensitivity'][allowance] for r in trials]
        known = [r for r in records if r['known_profile_recovered']['value'] is not None]
        profile[allowance] = dict(trials=len(records), known_truth_trials=len(known),
            selected_known_correct=sum(bool(r['known_profile_recovered']['value']) for r in known),
            known_truth_in_viable=sum(bool(r['truth_in_viable']['value']) for r in known),
            multiple_viable=sum(r['viable_count'] > 1 for r in records))
    compact = dict(schema='org.openjk.lighting-evaluation-witness.v1', metric_schema=result['schema'],
        run_sha256=digest(args.run), metric_source_sha256=result['source_sha256'],
        cases=cases, stock_readiness=stocks, compiled=compiled,
        analytical_source_sanity={name: dict(truth_count=r['oracle_source_sanity']['truth_count'],
            tp=r['oracle_source_sanity']['true_positive'], answer_sha256=r['answer_sha256'])
            for name, r in existing.get('analytical', {}).items()},
        boundary_35=existing['q3map2_boundary_35'], prior_x03_regret_sensitivity=profile,
        measurement=load(args.measurement),
        limitations=['No source fitting or new compiler/game run', 'Target-copy/source-copy controls are sanity assertions only',
            'Stock unknown transfer, primaries, profile and absolute scale', 'Unknown whole-map receiver area denominator',
            'API/artifact isolation is not an OS sandbox', 'No probability calibration on independent deployment scenes',
            'No new SP/MP build; production sources unchanged'])
    write(args.output/'summary.json', compact)
    lines = ['# Evaluation witness', '', 'Generated by `summarize.py`; detailed specification: '
        '[evaluation contract](../../../../docs/rend2-lighting-evaluation.md).', '',
        'No production solver was run. Oracle/source-copy checks below validate metric plumbing only.', '',
        '| Metric fixture | TP / FP / FN | Precision | Recall | RGB interval RMSE | Predicted area |',
        '|---|---|---|---|---|---|']
    for c in cases:
        lines.append(f'| {c["id"]} | {c["tp"]} / {c["fp"]} / {c["fn"]} | {c["precision"]["value"]} | '
                     f'{c["recall"]["value"]} | {c["rgb_interval_rmse"]["value"]} | {c["prediction_area_coverage"]["value"]} |')
    lines.extend(['', '## Stock readiness', '',
        'Fractions below use **known positive footprint area**, not entire-map area. Unknown-area texels are separate.', '',
        '| Map | Candidate texels | Known footprint area (world²) | No area | Mapped area / known area | Comparable linear colour area |',
        '|---|---|---|---|---|---|'])
    for name, r in stocks.items():
        q = r['qualities']
        lines.append(f'| {name} | {r["candidate_count"]} | {r["known_footprint_area"]:.3f} | {r["samples_without_area"]} | '
                     f'{q["mapped"]["fraction_of_known_footprint"]["value"]} | {q["comparable_colour"]["covered_area"]} |')
    lines.extend(['', 'Whole-map receiver-area coverage is NotComparable. Per-ray visibility is unmeasured without a source hypothesis.', '',
        '## Existing compiled observations', '',
        '| Scene | Candidate texels | Held-out samples | Zero byte-interval RMSE | Target-copy RMSE |',
        '|---|---|---|---|---|'])
    for name, r in compiled.items():
        lines.append(f'| {name} | {r["candidate_count"]} | {r["heldout_count"]} | '
                     f'{r["zero_interval_rmse"]["value"]} | {r["target_copy_interval_rmse"]["value"]} |')
    lines.extend(['', '## Boundary and profile diagnostics', '',
        'All 35 original boundary texels / 105 channels are retained; maximum old residual is 28 RGB8 units.', '',
        '| X03 regret allowance | Comparable trials | Known-profile selected correctly | Known truth retained | Multiple viable |',
        '|---|---|---|---|---|'])
    for allowance, r in profile.items():
        lines.append(f'| {allowance} | {r["trials"]} | {r["selected_known_correct"]}/{r["known_truth_trials"]} | '
                     f'{r["known_truth_in_viable"]}/{r["known_truth_trials"]} | {r["multiple_viable"]} |')
    lines.extend(['', 'These are prior X03 controls re-scored, not new fits or stock compiler classification.', '',
        'The existing skylight/wall_leak held-out folds have zero byte-interval error even for black predictions. '
        'These folds alone cannot establish useful localization information or physical-source recovery.', '',
        'The complete ten-section dashboard, JSON and CSV remain under the recorded local run folder.',
        'Actual OS peak working set and wall time are in `summary.json`; these measure the evaluator, not a solver.'])
    (args.output/'README.md').write_text('\n'.join(lines)+'\n', encoding='utf-8')


if __name__ == '__main__': main()
